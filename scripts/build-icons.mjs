// Extracts the Material Symbols (Apache-2.0) we use into a small typed map,
// so the app ships only the paths it needs instead of a 13MB icon font.
// Run: node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = "node_modules/@material-symbols/svg-400/rounded";
const NAMES = [
  "qr_code_scanner", "qr_code_2", "arrow_back", "close", "more_vert", "search", "add",
  "chevron_right", "shopping_bag", "av_timer", "account_balance", "settings",
  "help", "keyboard_arrow_up", "keyboard_arrow_down", "content_copy", "share", "edit",
  "backspace", "arrow_forward", "check", "check_circle", "flashlight_on", "flashlight_off",
  "image", "mobile", "receipt_long", "sync_alt", "alternate_email", "call", "person",
  "contacts", "tv", "lightbulb", "router", "mobile_ticket", "featured_seasonal_and_gifts", "school", "trophy", "redeem", "sell",
  "group_add", "notifications", "language", "lock", "shield", "logout", "info", "report",
  "credit_card", "add_card", "payments", "north_east", "south_west", "history", "dark_mode",
  "light_mode", "brightness_auto", "open_with", "verified", "error", "send", "warning",
  "schedule", "refresh", "storefront", "flight", "restaurant", "directions_bus", "local_mall",
  "celebration", "chat", "fingerprint", "visibility", "visibility_off", "delete", "upload",
  "download", "travel_explore", "sim_card", "chevron_left", "apps", "currency_rupee",
  "account_circle", "feedback", "block", "sentiment_satisfied", "trending_up", "bolt",
  "water_drop", "local_gas_station", "subscriptions", "movie", "devices", "science",
  "contactless", "request_quote", "call_received", "call_made", "do_not_disturb_on",
  "receipt", "person_add", "restart_alt", "support_agent", "mail", "quiz", "arrow_upward", "arrow_downward", "check_box", "add_circle", "local_atm", "savings", "wallet", "description", "dialpad", "hub", "undo", "home", "group",
];

const out = {};
for (const name of NAMES) {
  for (const variant of [name, `${name}-fill`]) {
    const svg = readFileSync(join(ROOT, `${variant}.svg`), "utf8");
    const ds = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
    if (!ds.length) throw new Error(`No path in ${variant}`);
    out[variant] = ds.join(" ");
  }
}

const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");
writeFileSync(
  "src/components/ui/icon-paths.ts",
  `// Generated by scripts/build-icons.mjs from Material Symbols Rounded (Apache-2.0). Do not edit.\n` +
    `export const ICON_PATHS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICON_PATHS;\n`,
);
console.log(`Wrote ${Object.keys(out).length} icons`);
